#!/usr/bin/env python3
"""Validate caller PR metadata without fetching or executing caller code."""
import argparse
import json
import os
from pathlib import Path
import re

# pr-title's default conventional types, plus exp for experiments.
BRANCH = re.compile(r"(?:feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert|exp)/[a-z0-9]+(?:-[a-z0-9]+)*\Z")
DATE = re.compile(r"(?:\d{4}-\d{2}-\d{2}|\d{2}-\d{2}-\d{4}|(?:19|20)\d{6})")
ISSUE = re.compile(r"(?<![\w/])(?:[\w.-]+/[\w.-]+)?#[1-9]\d*(?![\w])|"
                   r"https://github\.com/[\w.-]+/[\w.-]+/issues/[1-9]\d*(?![\w/])")
PLACEHOLDERS = {"n/a", "na", "none", "todo", "tbd", "reason", "specific reason", "no issue"}
REQUIRED_SECTIONS = ("Context", "Changes", "Testing Evidence", "Screenshots/Logs", "Rollback Plan")
# Squash merges append every commit's Co-authored-by line, so commit messages are checked, not only the PR body.
# Mirrors maios operations/conduct_review/rules/d8.py AI_ATTRIBUTION (trailer and footer patterns).
ATTRIBUTION = (
    ("AI Co-Authored-By trailer", re.compile(
        r"^[ \t]*co-authored-by[ \t]*:.*\b(?:claude|anthropic|gpt|openai|codex|cursor|copilot|gemini|kilo|grok"
        r"|assistant|agent|bot)\b", re.IGNORECASE | re.MULTILINE)),
    ("'Generated with/by' or 'Made with' footer", re.compile(
        r"^[^A-Za-z0-9\n]*(?:generated with\b|generated by\b(?!\s+scripts/)|made with\b)",
        re.IGNORECASE | re.MULTILINE)),
)


def uncomment_line(line, in_comment):
    """Remove comment spans, preserving HTML code blocks as literal text."""
    result = []
    offset = 0
    while offset < len(line):
        if in_comment:
            end = line.find("-->", offset)
            if end < 0:
                return "".join(result), True
            offset, in_comment = end + 3, False
            continue
        start = line.find("<!--", offset)
        html = re.search(r"<(pre|code)\b[^>]*>", line[offset:], re.I)
        if html and (start < 0 or offset + html.start() < start):
            close = re.search(rf"</{html[1]}\s*>", line[offset + html.end():], re.I)
            if not close:
                result.append(line[offset:])
                break
            end = offset + html.end() + close.end()
            result.append(line[offset:end])
            offset = end
        elif start < 0:
            result.append(line[offset:])
            break
        else:
            result.append(line[offset:start])
            offset, in_comment = start + 4, True
    return "".join(result), in_comment


def fenced_lines(body, *, respect_html=False, remove_comments=False):
    """Classify fenced lines while respecting list and quote containers."""
    fence = None
    html_code = None
    in_comment = False
    for line in body.splitlines():
        content = line.expandtabs(4)
        containers = []
        if fence:
            # Apply the opening containers in order, never literal code markers.
            for kind, width in fence[1]:
                quote = re.match(r"^ {0,3}> ?", content) if kind == "quote" else None
                if quote:
                    content = content[quote.end():]
                elif kind == "list" and (content.startswith(" " * width) or not content.strip()):
                    content = content[width:]
                else:
                    # This line starts a new outer block; examine it again below.
                    fence = None
                    content = line.expandtabs(4)
                    break
        if remove_comments and not fence and not html_code:
            preview = content
            while True:
                quote = re.match(r"^ {0,3}> ?", preview)
                item = re.match(r"^ {0,3}(?:[-+*]|\d+[.)])( +)", preview)
                if quote:
                    preview = preview[quote.end():]
                elif item:
                    end = item.start(1) + (1 if len(item[1]) > 4 else len(item[1]))
                    preview = preview[end:]
                else:
                    break
            if in_comment or not re.match(r"^ {0,3}(`{3,}|~{3,})", preview):
                line, in_comment = uncomment_line(line, in_comment)
                content = line.expandtabs(4)
        if respect_html and not fence:
            opening = re.search(r"<(pre|code)\b[^>]*>", line, re.I)
            if html_code or opening:
                tag = html_code or opening[1]
                html_code = None if re.search(rf"</{tag}\s*>", line, re.I) else tag
                yield line, content, "html"
                continue
        if not fence:
            while True:
                quote = re.match(r"^ {0,3}> ?", content)
                item = re.match(r"^ {0,3}(?:[-+*]|\d+[.)])( +)", content)
                if quote:
                    content = content[quote.end():]
                    containers.append(("quote", 0))
                elif item:
                    # Five or more padding spaces introduce indented code.
                    end = item.start(1) + (1 if len(item[1]) > 4 else len(item[1]))
                    content = content[end:]
                    containers.append(("list", end))
                else:
                    break
        match = re.match(r"^ {0,3}(`{3,}|~{3,})(.*)$", content)
        if fence:
            if (match and match[1][0] == fence[0][0] and len(match[1]) >= len(fence[0])
                    and not match[2].strip()):
                fence = None
                yield line, content, "close"
            else:
                yield line, content, "inside"
            continue
        if match:
            fence = (match[1], containers)
            yield line, content, "open"
        else:
            yield line, content, "text"


def strip_comments(body):
    """Remove comments without treating markers in code examples as comments."""
    return "\n".join(line for line, _, _ in fenced_lines(body, respect_html=True, remove_comments=True))


def prose(body):
    """Remove Markdown examples and comments before examining actual prose."""
    lines = []
    for _, content, kind in fenced_lines(strip_comments(body), respect_html=True):
        if kind in ("text", "html") and not content.startswith(" " * 4):
            lines.append(content)
    text = "\n".join(lines)
    text = re.sub(r"<(pre|code)\b[^>]*>.*?(?:</\1\s*>|\Z)", "", text, flags=re.S | re.I)
    return re.sub(r"(?<!`)(`+)(?!`).*?(?<!`)\1(?!`)", "", text, flags=re.S)


def linked(body):
    text = prose(body)
    if ISSUE.search(text):
        return True
    for match in re.finditer(r"^\s*No-issue:[ \t]*([^\n]*)$", text, flags=re.M | re.I):
        reason = match[1].strip()
        if (len(reason) >= 15 and len(reason.split()) >= 3
                and reason.lower().rstrip(".") not in PLACEHOLDERS
                and not re.search(r"[<>{}\[\]]|\b(?:todo|tbd|placeholder)\b", reason, re.I)):
            return True
    return False


def section_errors(body: str) -> list[str]:
    sections = {}
    heading = None
    html_code = None
    for line, _, kind in fenced_lines(strip_comments(body), respect_html=True):
        if kind not in ("text", "html"):
            if kind == "inside" and heading is not None:
                sections[heading].append(line)
            continue
        opening = re.search(r"<(pre|code)\b[^>]*>", line, re.I)
        if html_code or opening:
            tag = html_code or opening[1]
            html_code = None if re.search(rf"</{tag}\s*>", line, re.I) else tag
            if heading is not None:
                sections[heading].append(line)
            continue
        match = re.fullmatch(r" {0,3}##[ \t]+(.+?)\s*#*\s*", line)
        if match:
            heading = match[1].casefold()
            sections.setdefault(heading, [])
        elif heading is not None:
            sections[heading].append(line)
    errors = []
    for name in REQUIRED_SECTIONS:
        content = "\n".join(sections.get(name.casefold(), []))
        content = re.sub(r"(?m)^\s*[-*]\s*\[ \].*$", "", content)
        content = re.sub(r"<[^>]*>", "", content)
        lines = [line.strip(" \t#>*_`-.:\r") for line in content.splitlines()]
        if not any(re.search(r"[A-Za-z0-9]", line) and line.casefold() not in PLACEHOLDERS for line in lines):
            errors.append(f"Ready PR needs meaningful content in {name}.")
    return errors


def check(event: dict, *, require_sections: bool = False) -> list[str]:
    """Return violations; only a validated PR or explicit push can succeed."""
    if not isinstance(event, dict):
        return ["Event must be an object."]
    name = event.get("_event_name")
    if name == "push":
        if isinstance(event.get("ref"), str) and event["ref"].startswith("refs/") and "pull_request" not in event:
            return []
        return ["Malformed push event."]
    if name not in (None, "pull_request"):
        return ["Unsupported policy event."]
    pr = event.get("pull_request")
    if not isinstance(pr, dict):
        return ["Missing pull_request metadata."]
    user, head = pr.get("user"), pr.get("head")
    valid = (isinstance(user, dict) and isinstance(user.get("login"), str) and bool(user["login"])
             and user.get("type") in ("User", "Bot") and isinstance(head, dict)
             and isinstance(head.get("ref"), str) and bool(head["ref"])
             and type(pr.get("draft")) is bool and type(pr.get("number")) is int and pr["number"] > 0
             and type(event.get("number")) is int and event["number"] == pr["number"] and "body" in pr
             and (pr["body"] is None or isinstance(pr["body"], str))
             and event.get("action") in ("opened", "edited", "synchronize", "reopened",
                                          "ready_for_review", "converted_to_draft"))
    if not valid:
        return ["Malformed pull_request metadata."]
    branch = head["ref"]
    errors = []
    if not BRANCH.fullmatch(branch) or DATE.search(branch):
        errors.append("Branch must use a house type and a lowercase hyphenated topic without dates.")
    if not pr["draft"] and not linked(pr["body"] or ""):
        errors.append("Ready PR needs an issue reference or No-issue: followed by a specific reason.")
    if require_sections and not pr["draft"]:
        errors.extend(section_errors(pr["body"] or ""))
    return errors


def commit_errors(commits: list[dict]) -> list[str]:
    """Return one violation per attribution pattern that matches each commit message."""
    return [f"Commit {commit['sha'][:7]} has an {label}."
            for commit in commits for label, pattern in ATTRIBUTION if pattern.search(commit["message"])]


def read_commits(path: Path) -> list[dict]:
    """Read JSON Lines of {sha, message}; malformed records raise ValueError."""
    commits = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    if not all(isinstance(c, dict) and isinstance(c.get("sha"), str) and isinstance(c.get("message"), str)
               for c in commits):
        raise ValueError("malformed commit record")
    return commits


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--event", required=True, type=Path)
    parser.add_argument("--commits", type=Path, help="JSON Lines of {sha, message} fetched by the workflow")
    parser.add_argument("--require-sections", action="store_true",
                        default=os.environ.get("REQUIRE_SECTIONS") == "true")
    args = parser.parse_args()
    event = None
    try:
        event = json.loads(args.event.read_text(encoding="utf-8"))
        if isinstance(event, dict) and os.environ.get("GITHUB_EVENT_NAME"):
            event["_event_name"] = os.environ["GITHUB_EVENT_NAME"]
        errors = check(event, require_sections=args.require_sections)
    except (OSError, ValueError) as error:
        errors = [f"Cannot read event: {error.__class__.__name__}."]
    if args.commits is not None:
        try:
            commits = read_commits(args.commits)
            errors += commit_errors(commits)
            # The commits API stops at 250, so a shorter list than the event's count is never a pass.
            pr = event.get("pull_request") if isinstance(event, dict) else None
            total = pr.get("commits") if isinstance(pr, dict) else None
            if type(total) is not int or len(commits) != total:
                errors.append(f"Commit list has {len(commits)} of {total} PR commits.")
            # The API lists oldest first; a force-push after the event would end the list elsewhere.
            head = pr.get("head") if isinstance(pr, dict) else None
            if not commits or not isinstance(head, dict) or commits[-1]["sha"] != head.get("sha"):
                errors.append("Fetched commits do not end at the PR head.")
        except (OSError, ValueError) as error:
            errors.append(f"Cannot read commits: {error.__class__.__name__}.")
    for error in errors:
        print(f"::error::{error}")
    if not errors:
        print("PR policy compliant (or explicit non-PR push).")
    return int(bool(errors))


if __name__ == "__main__":
    raise SystemExit(main())
