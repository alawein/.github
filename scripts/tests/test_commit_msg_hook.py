"""Behavior fixtures for the local commit-msg hook that blocks AI attribution."""
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

HOOK = Path(__file__).resolve().parents[2] / "githooks" / "commit-msg"


def run_hook(message):
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False, encoding="utf-8") as handle:
        handle.write(message)
        path = handle.name
    try:
        return subprocess.run(["bash", str(HOOK), path], capture_output=True, text=True, check=False)
    finally:
        Path(path).unlink()


@unittest.skipUnless(shutil.which("bash"), "bash is required to run the hook")
class CommitMsgHookTests(unittest.TestCase):
    def test_rejects_ai_trailers_and_footers(self):
        bad = (
            "fix: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n",
            "fix: x\n\nCo-authored-by: Cursor Agent <cursoragent@cursor.com>\n",
            "fix: x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n",
            "fix: x\n\nMade with Copilot\n",
        )
        for message in bad:
            with self.subTest(message=message):
                self.assertEqual(run_hook(message).returncode, 1)

    def test_accepts_human_messages_and_comments(self):
        good = (
            "fix: x\n\nCo-authored-by: Jane Doe <jane@example.com>\n",
            "docs: note output generated by scripts/audit-hygiene.py\n",
            "fix: x\n# Co-authored-by: Claude (git comment line, stripped by git)\n",
        )
        for message in good:
            with self.subTest(message=message):
                self.assertEqual(run_hook(message).returncode, 0)


if __name__ == "__main__":
    unittest.main()
